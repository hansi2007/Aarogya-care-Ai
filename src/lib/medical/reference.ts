export function findReference(name: string): ReferenceEntry | null {
  const n = name.toLowerCase();
  let best: ReferenceEntry | null = null;
  let bestLen = 0;
  for (const entry of MEDICINE_REFERENCE) {
    for (const key of entry.match) {
      if (n.includes(key) && key.length > bestLen) {
        best = entry;
        bestLen = key.length;
      }
    }
  }
  return best;
}
